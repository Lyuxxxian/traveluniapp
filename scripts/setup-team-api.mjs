#!/usr/bin/env node
/**
 * 将管理端和 C 端都指向同一个共享后端。
 *
 * 用法：
 *   npm run team:api -- http://192.168.1.23:3000
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT_DIR = path.join(__dirname, '..')

function normalizeApiUrl(raw) {
  const value = String(raw || '').trim().replace(/\/+$/, '')
  if (!/^https?:\/\/[^/]+/i.test(value)) {
    throw new Error('请传入完整后端地址，例如 http://192.168.1.23:3000')
  }
  return value
}

function parseEnv(content) {
  const map = new Map()
  const passthrough = []
  for (const line of content.split(/\r?\n/)) {
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/)
    if (match) {
      map.set(match[1], match[2])
    } else if (line.trim()) {
      passthrough.push(line)
    }
  }
  return { map, passthrough }
}

function writeEnv(filePath, values) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : ''
  const { map, passthrough } = parseEnv(current)
  for (const [key, value] of Object.entries(values)) {
    map.set(key, value)
  }

  const lines = [
    '# Auto-generated by npm run team:api. Do not commit this file.',
    ...passthrough,
    ...Array.from(map.entries()).map(([key, value]) => `${key}=${value}`),
    '',
  ]

  fs.writeFileSync(filePath, lines.join('\n'), 'utf8')
}

try {
  const apiUrl = normalizeApiUrl(process.argv[2])

  writeEnv(path.join(ROOT_DIR, '.env.local'), {
    VITE_API_BASE_URL: apiUrl,
    VITE_MAP_USE_REMOTE_API: 'true',
    VITE_MALL_USE_REMOTE_API: 'true',
    VITE_HOME_USE_REMOTE_API: 'true',
    VITE_DISCOVER_USE_REMOTE_API: 'true',
    VITE_SERVICE_USE_REMOTE_API: 'true',
  })

  writeEnv(path.join(ROOT_DIR, 'admin-web/.env.local'), {
    VITE_API_BASE_URL: apiUrl,
  })

  console.log(`[team:api] 已配置共享后端: ${apiUrl}`)
  console.log('  已写入 .env.local 和 admin-web/.env.local')
  console.log('  请重启 admin-web 与 C 端 dev 服务')
} catch (error) {
  console.error(`[team:api] ${error.message}`)
  process.exit(1)
}
